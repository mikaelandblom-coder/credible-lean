#!/usr/bin/env python3
"""Write the paper's study figures (paper/figures/*.tex) from studies/runs/*.out.txt.

Each figure is a pgfplots `tikzpicture` with its coordinates inlined, read from
the study outputs, so a rerun of a study followed by

    python3 scripts/paper_figures.py

updates the figure. `--check` fails if a written figure differs from what the
outputs give (CI: the figures cannot drift from the studies).

  fig-blup.tex      S72/S74 (`blup-verdict.out.txt`): fitted BLUP − fitted blend,
                    with and without the balance shift, by ρ.
  fig-balance.tex   S75 (`balance-cost.out.txt`): the cross-fitted level's error
                    against the fit's own portfolio error, by σⱼ spread.
  fig-crossed.tex   S71 (`crossed-fit.out.txt`): REML and the thesis fit against
                    the inverse-variance pools, crossed tables.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "studies" / "runs"
OUT = ROOT / "paper" / "figures"

# Colours (a colour-blind-checked order: blue, orange, aqua), defined inside each
# tikzpicture: plasTeX's web build renders the picture alone, without the
# paper's \definecolor lines. Every series also has its own mark and line style,
# so identity is never colour alone.
COLORS = r"""\definecolor{figA}{HTML}{257DE0}%
\definecolor{figB}{HTML}{F47230}%
\definecolor{figC}{HTML}{00B894}%
"""

HEADER = "% Generated by scripts/paper_figures.py from studies/runs/{src}; do not edit.\n"

NUM = r"-?\d+(?:\.\d+)?"


def rows(path):
    """Table rows `name | a | b | ...` of a study output, as (name, [cells])."""
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if "|" not in line or not re.match(r"(app|thesis|\dx\d)", line):
            continue
        cells = [c.strip() for c in line.split("|")]
        out.append((cells[0], cells[1:]))
    return out


def world(name):
    """Parse 'app ρ=0.3 σⱼ×2 T=5' into a dict."""
    m = re.match(r"(\w+) ρ=([\d.]+) σⱼ×(\d) T=(\d+)", name)
    return dict(regime=m[1], rho=float(m[2]), spread=int(m[3]), T=int(m[4]))


def pm(cell):
    """'15.5 ± 4.6' or 'Δ bal 15.5 ± 4.6' -> (15.5, 4.6)."""
    m = re.search(rf"({NUM}) ± ({NUM})", cell)
    return float(m[1]), float(m[2])


def coords(points):
    return " ".join(f"({x:g},{y:g})" if e is None else f"({x:g},{y:g}) +- (0,{e:g})"
                    for x, y, e in points)


# --- Figure 1: BLUP − blend, balanced and not (S72, S74) ---------------------

def fig_blup():
    src = "blup-verdict.out.txt"
    table = rows(RUNS / src)
    # The file has two tables with the same world names: first balanced
    # (Δ BLUP in column 7), then raw (Δ BLUP raw in column 4).
    n = len(table) // 2
    bal = {name: pm(c[6]) for name, c in table[:n]}
    raw = {name: pm(c[3]) for name, c in table[n:]}
    series = {}
    for name in bal:
        w = world(name)
        if w["T"] != 5 or w["spread"] not in (0, 2) or w["regime"] not in ("app", "thesis"):
            continue
        key = (w["regime"], w["spread"])
        series.setdefault(key, {"bal": [], "raw": []})
        series[key]["bal"].append((w["rho"], *bal[name]))
        series[key]["raw"].append((w["rho"], *raw[name]))

    style = {0: ("figA", "*"), 2: ("figB", "square*")}

    def panel(regime, title, legend):
        opts = (r", ylabel={BLUP $-$ blend (points of the floor)}, legend style={font=\footnotesize,"
                r" at={(1.12,-0.3)}, anchor=north, legend columns=2, draw=none,"
                r" /tikz/every even column/.append style={column sep=1em}}") if legend else ""
        s = [rf"\nextgroupplot[title={{{title}}}{opts}]"]
        for spread in (0, 2):
            col, mark = style[spread]
            lab = "equal $\\sigma_j$" if spread == 0 else "$\\sigma_j$ spread 2"
            for kind, dash, word in (("raw", "solid", "not shifted"),
                                     ("bal", "dashed", "shifted to balance")):
                pts = [(x, y, e) for x, y, e in series[(regime, spread)][kind]]
                s.append(rf"\addplot+[{col}, {dash}, mark={mark}, mark options={{solid, fill={col}}},"
                         r" error bars/.cd, y dir=both, y explicit] coordinates {" + coords(pts) + "};")
                if legend:
                    s.append(rf"\addlegendentry{{{lab}, {word}}}")
        s.append(r"\addplot[gray, thin, forget plot] coordinates {(-0.05,0) (0.95,0)};")
        return "\n".join(s)

    body = HEADER.format(src=src) + r"""\begin{tikzpicture}
""" + COLORS + r"""\begin{groupplot}[group style={group size=2 by 1, horizontal sep=1.4cm},
  width=0.47\textwidth, height=0.36\textwidth,
  xmin=-0.05, xmax=0.95, xtick={0,0.3,0.6,0.9},
  xlabel={correlation $\rho$},
  ylabel style={font=\footnotesize}, xlabel style={font=\footnotesize},
  tick label style={font=\footnotesize}, title style={font=\small},
  error bars/error bar style={thin}, every axis plot/.append style={thick},
  legend cell align=left]
""" + panel("app", "app volume", True) + "\n" + panel("thesis", "thesis volume", False) + r"""
\end{groupplot}
\end{tikzpicture}
"""
    return body


# --- Figure 2: cost of balancing by σⱼ spread (S75) --------------------------

def fig_balance():
    src = "balance-cost.out.txt"
    pts = {"app": [], "thesis": [], "thesisShape": []}
    for name, c in rows(RUNS / src):
        w = world(name)
        ratio = float(c[1]) / float(c[2])
        pts[w["regime"]].append((w["spread"], ratio))
    shift = {"app": -0.12, "thesis": 0.0, "thesisShape": 0.12}
    style = {"app": ("figA", "*"), "thesis": ("figB", "square*"), "thesisShape": ("figC", "triangle*")}
    label = {"app": "app volume", "thesis": "thesis volume", "thesisShape": "thesis shape"}
    s = []
    for reg in ("app", "thesis", "thesisShape"):
        col, mark = style[reg]
        cs = " ".join(f"({x + shift[reg]:g},{y:.3f})" for x, y in pts[reg])
        s.append(rf"\addplot[only marks, mark={mark}, mark size=1.8pt, draw=white, fill={col}, line width=0.3pt]"
                 " coordinates {" + cs + "};")
        s.append(rf"\addlegendentry{{{label[reg]}}}")
    return HEADER.format(src=src) + r"""\begin{tikzpicture}
""" + COLORS + r"""\begin{axis}[width=0.62\textwidth, height=0.42\textwidth,
  xmin=-0.5, xmax=2.5, xtick={0,1,2},
  xticklabels={equal $\sigma_j$, spread 1, spread 2},
  ymin=0.7, ymax=2.35,
  xlabel={noise-variance spread across cohorts},
  ylabel={$E(T-\bar\mu)^2 / E(\bar r-\bar\mu)^2$},
  ylabel style={font=\footnotesize}, xlabel style={font=\footnotesize},
  tick label style={font=\footnotesize},
  legend style={font=\footnotesize, at={(0.03,0.97)}, anchor=north west, draw=none},
  legend cell align=left]
\addplot[gray, thin, forget plot] coordinates {(-0.5,1) (2.5,1)};
\node[font=\scriptsize, gray, anchor=south east] at (axis cs:2.45,1) {balancing pays below};
""" + "\n".join(s) + r"""
\end{axis}
\end{tikzpicture}
"""


# --- Figure 3: crossed default against the pools (S71) -----------------------

def fig_crossed():
    src = "crossed-fit.out.txt"
    text = (RUNS / src).read_text(encoding="utf-8").splitlines()
    head = next(l for l in text if l.startswith("world"))
    cols = [c.strip() for c in head.split("|")][1:]
    ii, ir, it = cols.index("iv-clip"), cols.index("reml"), cols.index("thesis")
    reml, thesis = [], []
    for name, c in rows(RUNS / src):
        if not re.match(r"\dx\d", name):
            continue
        x = float(c[ii])
        reml.append((x, float(c[ir])))
        thesis.append((x, float(c[it])))
    assert len(reml) == 96, len(reml)

    def panel(pts, col, mark, title, top):
        cs = " ".join(f"({x:g},{y:g})" for x, y in pts)
        return (rf"\nextgroupplot[title={{{title}}}, xmin=100, xmax={top}, ymin=100, ymax={top}]" + "\n"
                + rf"\addplot[gray, thin] coordinates {{(100,100) ({top},{top})}};" + "\n"
                + rf"\addplot[only marks, mark={mark}, mark size=1.6pt, draw=white, fill={col}, line width=0.3pt]"
                " coordinates {" + cs + "};")

    return HEADER.format(src=src) + r"""\begin{tikzpicture}
""" + COLORS + r"""\begin{groupplot}[group style={group size=2 by 1, horizontal sep=1.4cm},
  width=0.47\textwidth, height=0.47\textwidth,
  xlabel={pools, \% of the floor}, ylabel={fit, \% of the floor},
  ylabel style={font=\footnotesize}, xlabel style={font=\footnotesize},
  tick label style={font=\footnotesize}, title style={font=\small}]
""" + panel(reml, "figA", "*", "REML on the cell means", 240) + "\n" \
        + panel(thesis, "figB", "square*", "thesis fit", 420) + r"""
\end{groupplot}
\end{tikzpicture}
"""


FIGURES = {"fig-blup.tex": fig_blup, "fig-balance.tex": fig_balance, "fig-crossed.tex": fig_crossed}


def main():
    check = "--check" in sys.argv
    OUT.mkdir(exist_ok=True)
    bad = []
    for name, make in FIGURES.items():
        body = make()
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != body:
                bad.append(name)
        else:
            path.write_text(body, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if bad:
        print("out of date (run scripts/paper_figures.py):", ", ".join(bad))
        sys.exit(1)


if __name__ == "__main__":
    main()
